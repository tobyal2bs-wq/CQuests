# Outward is +z rotation for the left limbs (+x side) and -z for the right ones. The tables above were
# written the other way round, so flip z on the side limbs once here.
def _flip(rig, names):
    for anim in rig.values():
        for bone, ch in anim["bones"].items():
            if any(bone.startswith(n) for n in names) and "rot" in ch:
                for k in ch["rot"]:
                    k[1][2] = -k[1][2]
